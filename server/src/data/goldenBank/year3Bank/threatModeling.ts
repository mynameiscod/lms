/**
 * THREAT_MODELING — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can look at a design and work out how it would be attacked, before any of
 * it is built. [[web-security]] and [[secure-coding]] are about recognising and avoiding known
 * problems in code; this is the step earlier — deciding what is worth protecting and from whom,
 * so that the effort goes to the right place.
 *
 * Bands: name the pieces, explain why the exercise is done at design time, apply it to a
 * described system, diagnose a threat model that is not working, and judge its limits.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That a threat model is a conversation with an output, not a document for its own sake. The
 * value is in the questions being asked by the people who will build the thing; a thorough
 * model nobody read has produced nothing.
 *
 * That "what are we building, what can go wrong, what do we do about it, did we do a good job"
 * is enough structure for most teams. The formal methodologies are useful and are not the point,
 * and a student who thinks the acronym is the skill will not do this at all.
 *
 * And that assets and attackers must be named concretely. "Protect the system from hackers" is
 * not a threat model; "stop a customer reading another customer's invoices" is one, because you
 * can test whether you did it.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

