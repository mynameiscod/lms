/**
 * SECURITY_FUNDAMENTALS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student writes code that does not hand the system away. Not whether they can name
 * the OWASP Top Ten, which is the thing courses assess and which predicts nothing about the
 * code somebody actually writes.
 *
 * Bands: name the attacks, explain the mechanism, apply the defence, diagnose a system that has
 * been designed around a false assumption, and judge where security decisions actually sit.
 *
 * ── THE TWO POSITIONS THIS TAKES ──────────────────────────────────────────────────────────
 *
 * That nearly every injection is one mistake wearing different clothes: data was allowed to
 * become instructions. SQL injection, XSS and command injection are the same failure in three
 * languages, and the defence is the same shape each time — keep the two apart structurally
 * rather than trying to spot dangerous input. D5 rests on that.
 *
 * And that the client is not a security boundary. A hidden field, a disabled button, a
 * front-end check, a price sent from the browser: all of them are requests, and all of them can
 * be forged with a tool anyone can install. Several D4 items are that assumption failing in
 * production.
 */

