/**
 * Golden Bank blueprint — Batch 4: scripting, the page as data, the protocol, and C.
 *
 * JS_BASICS AND JS_DOM ARE DELIBERATELY SEPARATED. One measures the language — values, types,
 * functions, arrays, the equality rules that catch everybody. The other measures the page as a
 * live object — finding elements, changing them, responding to events. A student can be fluent in
 * one and helpless in the other, and a paper that mixes them cannot tell you which.
 *
 * HTTP IS MEASURED AS AN EXCHANGE, NOT AS A TABLE OF NUMBERS. Not "what is 404" but "given this
 * symptom, which side is at fault"; not "list the methods" but "which method should this action
 * use and why". Status codes appear because they are evidence, never because they are memorable.
 *
 * C EXISTS HERE FOR THE ACADEMIC SYLLABUS AND IS MEASURED WHERE IT DIFFERS FROM PYTHON — types
 * declared up front, integer division, fixed-size arrays, the assignment-in-a-condition trap,
 * and the fact that reading past the end of an array is not an error that stops you. Anything
 * that behaves the same in both languages is measured once, in the Python or fundamentals skill,
 * not twice.
 *
 * Code appears in the stem throughout. All items stay mcq_single.
 */

