/**
 * DSA_DIVIDE_CONQUER — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can recognise a problem that splits, and reason about what the split
 * costs. Divide and conquer is the shape behind binary search, merge sort, quicksort and a
 * great many interview problems, and the students who have only memorised those four cannot
 * apply it to the fifth.
 *
 * Bands: name the parts, explain why splitting helps, apply it to a described problem,
 * diagnose a recursion that is wrong or slow, and judge when the split is not worth it.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That the combine step is where the cost lives. Students focus on the split and forget that
 * merge sort's O(n log n) comes from doing O(n) work at each of log n levels — the recursion
 * is free and the merging is not.
 *
 * That the difference between [[dsa-dp]] and this one is whether the subproblems overlap. Both
 * break a problem into smaller ones; only DP has anything worth caching, and knowing which you
 * are looking at decides the whole approach.
 *
 * And that an unbalanced split destroys the benefit. Quicksort's worst case is not bad luck in
 * the abstract — it is what happens when every split takes one element off the end, and that
 * turns log n levels into n.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

