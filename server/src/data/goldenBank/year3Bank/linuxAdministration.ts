/**
 * LINUX_ADMINISTRATION — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can work on a server they did not set up. Not memorised commands — those
 * are looked up — but the model underneath: processes, permissions, the filesystem, what is
 * consuming a resource, and how to find out rather than guess.
 *
 * Bands: name the pieces, explain why the system behaves as it does, apply that to a described
 * situation, diagnose a server that is misbehaving, and judge the operational calls.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That diagnosis is a sequence, not a guess: which resource is exhausted, which process is
 * using it, and why. Students reach for a remembered command; the skill is knowing which
 * question to ask first.
 *
 * That permissions are the commonest cause of "it works locally". Ownership, the permission
 * bits and the user a service runs as explain most deployment failures on a Linux box.
 *
 * And that a file being deleted does not free its space while a process holds it open. This is
 * the single most confusing disk-space situation a junior engineer meets, and it is here at
 * two bands because it reliably separates understanding from memorisation.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

