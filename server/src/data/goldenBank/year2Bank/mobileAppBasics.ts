/**
 * MOBILE_APP_BASICS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can reason about software running on a device they do not control, owned
 * by somebody who is walking around. Not the API surface of one framework — that is looked up
 * and changes — but the constraints every mobile platform imposes and the assumptions a web
 * developer brings that do not survive them.
 *
 * Bands: name the pieces, explain why the platform behaves as it does, build for a stated
 * requirement, diagnose the failures that only appear on real devices, and judge the calls
 * that have no universally right answer.
 *
 * ── THE THREE POSITIONS THIS TAKES ────────────────────────────────────────────────────────
 *
 * That the app does not own the device. The operating system will suspend it, kill it, rotate
 * it, deny it permissions and take the network away, and none of those are errors. Handling
 * them is the job; a web developer's habits assume none of them happen.
 *
 * That the network is unreliable by default, not occasionally. Offline, slow and expensive are
 * the normal cases on a phone, and an app designed for the office wi-fi fails on a train.
 *
 * And that an old version lives forever. You cannot deploy a fix to everybody the way a website
 * can, so the server must go on speaking to versions shipped a year ago. D4 and D5 return to
 * that repeatedly.
 */

