/**
 * Golden Bank blueprint — Batch 1: the five skills the Foundation year opens with.
 *
 * WHAT A ROW IS. One fact, measured one way. factId names a piece of knowledge or capability;
 * familyId names the single measurement that probes it. Both are unique across the batch, which
 * is deliberate: it forces every row to justify itself as a distinct measurement rather than as
 * another wording of a neighbour. Clustering lives in reassessmentGroup, where it belongs —
 * that is what stops a re-assessment serving an equivalent measurement and reading the
 * remembered answer as progress.
 *
 * WHY NOT FIVE DIFFICULTIES PER FACT. Because difficulty is a property of the QUESTION FAMILY,
 * not a dial. "Which component performs arithmetic" cannot be made a D5 question by adding
 * words; asking it at D5 would only add reading. So each family carries the range it can
 * honestly span, and several facts span two levels rather than five. The bank this replaces
 * reached forty thousand rows precisely by pretending otherwise.
 *
 * DISTRACTORS NAME MISCONCEPTIONS. Every distractorStrategy describes a belief a real first-year
 * actually holds — the CPU stores files, more RAM makes the processor faster, decode comes before
 * fetch. The bank being replaced used absurdities ("RAM is full", "stop the OS"), which are
 * answerable by elimination and therefore measure nothing: a student who knows none of the
 * material still scores by spotting the silly option.
 *
 * COGNITIVE LEVEL IS NOT DIFFICULTY. A REMEMBER item can be hard if the fact is obscure, and an
 * ANALYZE item can be easy if the analysis is short. They are recorded separately because they
 * answer different questions: what the student must DO, and how demanding it is.
 */

export interface BlueprintRow {
  skillKey: string;
  conceptId: string;
  conceptName: string;
  factId: string;
  factStatement: string;
  familyId: string;
  familyName: string;
  measurementObjective: string;
  allowedDifficultyMin: 'D1' | 'D2' | 'D3' | 'D4' | 'D5';
  allowedDifficultyMax: 'D1' | 'D2' | 'D3' | 'D4' | 'D5';
  cognitiveLevel: 'REMEMBER' | 'UNDERSTAND' | 'APPLY' | 'ANALYZE' | 'EVALUATE';
  questionType: string;
  distractorStrategy: string;
  reassessmentGroup: string;
  notes: string;
}

