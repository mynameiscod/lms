/**
 * BEHAVIORAL_INTERVIEW — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can answer questions about their own work in a way an interviewer can
 * assess. This is a Year-3 placement skill, and the students who lose offers here are usually
 * technically fine: they fail because they cannot say what they personally did, or what they
 * would do differently, or why anybody should believe the story.
 *
 * Bands: name the shape of a good answer, explain why interviewers ask this way, apply it to a
 * described question, diagnose an answer that will score badly, and judge the hard cases —
 * failure, conflict, and not having the experience being asked about.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That the interviewer is assessing you, not your team. "We decided" and "we built" is the
 * commonest fatal habit, because the answer contains no evidence about the candidate at all.
 *
 * That specifics are what make an answer credible. Named numbers, named constraints and named
 * trade-offs are hard to fake and easy to probe, which is exactly why they are believed.
 *
 * And that an honest failure answered well scores higher than a disguised success. "My biggest
 * weakness is I work too hard" is a refusal to engage, and every interviewer recognises it.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

