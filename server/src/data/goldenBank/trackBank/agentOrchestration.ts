/**
 * AGENT_ORCHESTRATION — fifty items, ten at each band. Question ids GBT_AGO_001 … GBT_AGO_050.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can build agents as explicit state graphs that survive real conditions:
 * typed state, nodes that return updates, reducers and the one-write-per-step rule, routers that
 * are plain tests on state fields, checkpoints per thread; a supervisor with specialists, shared
 * versus private state, hand-off notes and turn caps; parallel fan-out and fan-in, Send payloads,
 * joins keyed by id, concurrency caps and per-error handling; human approval with interrupt and
 * resume, nodes that re-run on resume, state correction and approval services; and durable
 * execution — shared checkpointers, durability modes, retry policies, time-outs and idempotent
 * side effects.
 *
 * The course builds these in LangGraph and the items use its names (Command, Send, interrupt,
 * update_state, RetryPolicy); the ideas transfer to any orchestration framework.
 *
 * Bands: name the pieces, explain why each behaves as it does, apply them to a described graph,
 * diagnose a graph that misbehaved from its symptoms, and judge an orchestration design.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That every decision the program makes should be a field in state and every arrow a short test
 * on it — deterministic, free and unit-testable.
 *
 * That several agents must earn their extra calls with a concrete reason, such as isolating a
 * sensitive tool, and that every hand-off loop has a cap and an honest exit.
 *
 * That a node may run more than once — after a crash, a retry or a resume — so checkpoints
 * shrink repeated work and idempotency keys make what is repeated harmless; neither replaces
 * the other.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

