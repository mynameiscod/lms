/**
 * CI_CD — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student understands what a pipeline is FOR, not how to write YAML for one. The
 * syntax differs between every tool and is looked up; the reasoning — what should block a
 * merge, what a red build means, why a slow pipeline is a correctness problem — transfers.
 *
 * Bands: name the stages, explain what continuous integration actually asks of a team, apply
 * it to a described project, diagnose a pipeline that has stopped being useful, and judge the
 * trade-offs between speed and confidence.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That continuous integration is a team practice, not a server. Merging to the mainline often
 * is the practice; the server is what checks it. A team with a pipeline and three-week branches
 * is not doing CI, and that distinction is the point of the D2 band.
 *
 * That a pipeline nobody trusts is worse than none, for the same reason a flaky test is worse
 * than no test — once red might mean nothing, red means nothing. This deliberately echoes
 * [[automated-testing]], because it is the same failure at a different scale.
 *
 * And that build speed is not a comfort issue. A pipeline slow enough to context-switch away
 * from changes how people work, and they start batching changes, which is the opposite of what
 * the practice asks for.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

