// Scope the Tailwind + DevNexus base output to .visualizer-theme so it cannot leak into the LMS,
// flatten nesting and cascade layers (the LMS CSS is unlayered), and win over Bootstrap's
// !important utilities where class names collide (gap-5, p-3, border, rounded, shadow-sm...).
import fs from 'node:fs';
import postcss from 'postcss';
import { transform, browserslistToTargets } from 'lightningcss';
const [,, input, output] = process.argv;
const bootstrap = new Set(JSON.parse(fs.readFileSync(new URL('./bs-important.json', import.meta.url))));
const targets = { chrome: 100 << 16, firefox: 100 << 16, safari: (15 << 16) | (4 << 8), edge: 100 << 16 };
const flat = transform({ filename: 'in.css', code: fs.readFileSync(input), targets, minify: false }).code.toString();
const SCOPE = ':where(.visualizer-theme)';
// Split a selector list on top-level commas, ignoring escaped ones (`.grid-cols-\[minmax\(0\,1fr\)\]`).
const splitSelectors = sel => {
  const parts = []; let depth = 0, current = '';
  for (let i = 0; i < sel.length; i++) {
    const ch = sel[i];
    if (ch === '\\') { current += ch + (sel[i + 1] ?? ''); i++; continue; }
    if (ch === '(') depth++; else if (ch === ')') depth--;
    if (ch === ',' && depth === 0) { parts.push(current); current = ''; } else current += ch;
  }
  parts.push(current);
  return parts;
};
const scopeSelector = sel => splitSelectors(sel).map(s => {
  s = s.trim();
  if (/^(:root|:host|html|body)$/.test(s) || /^(:root|html),\s*:host$/.test(s)) return SCOPE;
  if (/^(html|:host|body)\b/.test(s)) return s.replace(/^(html|:host|body)/, SCOPE);
  return `${SCOPE} ${s}`;
}).join(', ');
const root = postcss.parse(flat);
// Unwrap @layer blocks and drop layer-order statements.
root.walkAtRules('layer', at => { if (at.nodes) at.replaceWith(at.nodes); else at.remove(); });
root.walkRules(rule => {
  const parent = rule.parent;
  if (parent && parent.type === 'atrule' && /keyframes$/.test(parent.name)) return;
  const classes = [...rule.selector.matchAll(/^\.((?:\\.|[\w-])+)/gm)].map(m => m[1].replace(/\\/g, ''));
  const collides = classes.some(c => bootstrap.has(c));
  rule.selector = scopeSelector(rule.selector);
  if (collides) rule.walkDecls(d => { if (!d.prop.startsWith('--')) d.important = true; });
});
fs.writeFileSync(output, `/* GENERATED by core/theme/tailwind/build.sh — do not edit by hand.\n * Tailwind v4 utilities used by the DSA Visualizer, CodeBegun palette, scoped to .visualizer-theme. */\n` + root.toString());
