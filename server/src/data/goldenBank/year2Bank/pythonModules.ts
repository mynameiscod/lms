/**
 * PYTHON_MODULES — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can organise a program across more than one file, and depend on somebody
 * else's code without it becoming a liability. Year 1 teaches `import`; this is the second-year
 * question of what importing actually does, where the boundaries between files should fall, and
 * what a dependency costs once it is in a project.
 *
 * Bands: name the pieces, explain what import does and when, structure a project for a stated
 * need, diagnose the failures — circular imports, shadowed standard library names, code that
 * runs on import — and judge the calls about dependencies and boundaries.
 *
 * ── THE THREE POSITIONS THIS TAKES ────────────────────────────────────────────────────────
 *
 * That importing a module RUNS it. Every statement at the top level executes the first time the
 * module is imported, once, and whatever that does — opening a connection, reading a file,
 * printing — happens as a side effect of somebody typing `import`.
 *
 * That the module boundary is a design decision, not a filing decision. Files named after what
 * they contain rather than what they do — utils, helpers, common — become the place everything
 * lands, and then everything imports everything.
 *
 * And that a dependency is a commitment. It brings its own dependencies, its own release
 * schedule and its own bugs, and left unpinned it can change under a project that has not.
 */

