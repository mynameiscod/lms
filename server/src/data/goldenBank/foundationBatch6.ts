/**
 * Golden Bank blueprint — Batch 6: reasoning, communication, career, and debugging as a method.
 *
 * These are the eight least like the others, and three of them needed a decision before a single
 * family could be written.
 *
 * DEBUGGING HAD TO EARN ITS PLACE. Twenty-four skills already carry a diagnosis family — why is
 * this style not applied, why is my change not on the remote, why did the loop run once too
 * often. If DEBUGGING measured more of those it would be measuring nothing new, and a student
 * strong at Python diagnosis would score well without ever having debugged systematically. So it
 * measures the METHOD instead, in a way no domain family does: what would reproduce this, which
 * hypothesis the evidence actually supports, which single change narrows the search, why changing
 * three things at once destroys the information you were gathering, and whether a fix has been
 * demonstrated or merely coincides with the symptom disappearing. Every stem is domain-light on
 * purpose — the fault is stated, and the measurement is what you do next.
 *
 * THE THREE COMMUNICATION SKILLS ARE MADE DISCRIMINATING BY ASKING ABOUT DEFECTS, NOT QUALITY.
 * "Which explanation is best" is a taste question with four defensible answers. "Which of these
 * four instructions could be followed in two different ways", "what does this bug report fail to
 * say", "where does this analogy stop being true", "which rewrite fixes THIS specific defect" —
 * each has one right answer that a reader can verify from the text. Every family in
 * TECHNICAL_COMMUNICATION, TECHNICAL_EXPLANATION and TECH_CAREER_AWARENESS is framed that way,
 * and any family that could only be settled by preference was not written.
 *
 * TECH_CAREER_AWARENESS IS ABOUT EVIDENCE, NOT ADVICE. Not "should you do an internship" but
 * "which of these claims can an employer verify", "does this project demonstrate the skill it
 * claims", "what does this CV assert that nothing in it supports". Career opinion is unmeasurable
 * and would date within a year; the reasoning about evidence does not.
 *
 * THE VISUAL SKILLS ARE DESCRIBED, NOT DRAWN. PATTERN_RECOGNITION and the series families cannot
 * use images, so every pattern is expressed as a symbol string, a grid of coordinates, or a
 * stated sequence. That is a genuine constraint and it rules out some classic item types — but it
 * rules out exactly the ones that measure visual acuity rather than the structure underneath.
 */

