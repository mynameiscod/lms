/**
 * INTERNSHIP_READINESS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * The gap between being able to write code and being able to hold a job. It is a real gap and
 * most students fall into it in their first fortnight, not because they cannot program but
 * because nobody told them how long to stay stuck, what a standup is for, or that "I don't
 * know" is an acceptable sentence.
 *
 * This measures judgement about working inside a team, which a paper can test. It does not
 * measure whether the student has done an internship — nothing here rewards having had one.
 * PORTFOLIO_EVIDENCE covers how work is presented; TECHNICAL_INTERVIEW_PREP covers the
 * interview itself. This bank starts on day one of the job and stays there.
 *
 * ── THE THREE POSITIONS THIS TAKES ────────────────────────────────────────────────────────
 *
 * That being stuck is normal and staying stuck silently is the failure. An intern is expected
 * to ask; the only real mistake is the fourth day of the same problem with nobody told.
 *
 * That most of the work is not writing code. It is reading code, understanding what is wanted,
 * and saying clearly what you have done and what you have not. Students arrive expecting the
 * opposite ratio.
 *
 * And that an intern is judged on trajectory, not on output. Nobody expects speed in week one.
 * They expect the same mistake not to appear in week four — which makes how you take feedback
 * more consequential than how much you ship.
 */

