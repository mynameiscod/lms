/**
 * DSA_HEAPS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student reaches for a heap at the right moment. A heap is a narrow tool: it gives
 * you the smallest or largest item cheaply and repeatedly, and gives you nothing else. Knowing
 * that narrowness is the skill, because the alternative — sorting everything, or scanning for
 * the minimum each time — is what most students do instead.
 *
 * Bands: name what it gives you, explain why the cost is what it is, apply it to a described
 * problem, diagnose a heap used wrongly, and judge when a heap is not the answer at all.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That a heap is ordered only at the top. Students routinely assume iterating a heap yields
 * sorted order, or that the second-smallest is in a known place; both are false and both cost
 * marks. Several items exist purely to catch that.
 *
 * That the k-largest idiom uses a MIN heap, which feels backwards and is the most valuable
 * single pattern in this skill. It appears three times across the bands, from different angles.
 *
 * And that building a heap from n items costs O(n), not O(n log n). It is the one complexity
 * result here that is genuinely surprising, and it changes which approach wins.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

