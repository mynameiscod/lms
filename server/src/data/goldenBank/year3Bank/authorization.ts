/**
 * AUTHORIZATION — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can answer "may this identity do this?" in the right place, every time. The
 * companion to AUTHENTICATION: that skill establishes who is asking, this one decides what the
 * answer entitles them to. Students who have only met login treat this as a role check in a
 * middleware, which is exactly the mistake the D4 band is built to catch.
 *
 * Bands: name the model, explain why the check belongs where it does, apply it to a described
 * feature, diagnose the holes that show up in real systems, and judge policies that are
 * defensible either way.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That the check belongs on the server, next to the data, and that hiding a button is a courtesy
 * to the user rather than a control. A quarter of these items reduce to that.
 *
 * That the most common real hole is not a missing role check but a missing ownership check —
 * a logged-in user reading another user's record by changing a number in the URL.
 *
 * And that deny-by-default is the only workable posture, because a list of what is forbidden is
 * never finished while a list of what is permitted can be.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options within an item are kept to similar lengths on purpose; the suite fails a bank where
 * correct answers run long, since that measures test-taking rather than the skill.
 */

