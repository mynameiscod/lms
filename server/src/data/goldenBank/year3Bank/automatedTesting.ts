/**
 * AUTOMATED_TESTING — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can build a suite a team will actually trust. TESTING_FUNDAMENTALS (Year 2)
 * covers what a test is and how to write one; this is the level above — what to test, at which
 * level, and what to do when the suite starts lying to you.
 *
 * Bands: name the levels, explain what each buys, apply them to a described system, diagnose a
 * suite that has gone bad, and judge the trade-offs that have no textbook answer.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That a flaky test is worse than no test. Once a red build might mean nothing, the team stops
 * reading red builds, and every other test in the suite loses its power at the same moment.
 * Two items make that explicit because students consistently rank flakiness as a minor annoyance.
 *
 * That coverage is a map of what was executed, not of what was checked. A suite can run every
 * line and assert almost nothing, and the number will look excellent.
 *
 * And that tests should assert on behaviour, not on how the behaviour was produced. A test that
 * knows the internals turns the safety net into a straitjacket — the same failure mode
 * [[refactoring]] runs into from the other side.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

