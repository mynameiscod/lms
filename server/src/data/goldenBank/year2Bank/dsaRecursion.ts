/**
 * DSA_RECURSION — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can tell when a problem is genuinely recursive and when recursion is
 * decoration on a loop. Not whether they can trace factorial(5) by hand, which every course
 * assesses and which measures arithmetic rather than judgement.
 *
 * Bands: name the parts, trace what happens, write a correct recursion for a given shape,
 * diagnose one that overflows or recomputes, and judge when the loop is the better answer.
 *
 * ── THE TWO POSITIONS THIS TAKES ──────────────────────────────────────────────────────────
 *
 * That recursion earns its place on branching data — trees, nested structures, directories,
 * anything where the shape is unknown at the time of writing. On a flat list it is a loop with
 * a stack frame per element and a crash waiting for a large input, and several D5 items say so
 * directly.
 *
 * And that the two failure modes are structural rather than careless. Stack overflow comes from
 * depth proportional to the input; exponential blow-up comes from a call tree that recomputes
 * the same subproblem. Both look fine on small inputs, which is what D4 is built around.
 */

