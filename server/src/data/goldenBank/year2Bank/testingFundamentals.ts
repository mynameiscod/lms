/**
 * TESTING_FUNDAMENTALS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can write tests that would actually catch the bug, and tell a useful suite
 * from a decorative one. Not whether they can define the testing pyramid, which is the thing
 * courses assess and which says nothing about whether anybody trusts the build.
 *
 * Bands: name the kinds, explain what each is for, write a test for a given case, diagnose a
 * suite that has stopped being believed, and judge what testing is actually buying.
 *
 * ── THE TWO POSITIONS THIS TAKES ──────────────────────────────────────────────────────────
 *
 * That coverage measures execution, not verification. A test that runs a line and asserts
 * nothing about it counts exactly the same as one that checks the answer, so a percentage is a
 * floor on what was missed and never a statement about what was checked. D4 and D5 both lean
 * on that.
 *
 * And that a flaky test is worse than no test. It trains a team to ignore red, and once
 * ignoring red is normal the suite has stopped being a safety net whatever its coverage says.
 * That is the failure mode worth recognising, because it arrives gradually.
 */

