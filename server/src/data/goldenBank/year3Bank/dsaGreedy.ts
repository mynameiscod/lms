/**
 * DSA_GREEDY — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can tell when taking the locally best option gives the globally best
 * answer, and — more importantly — when it does not. Greedy is the easiest strategy to write
 * and the easiest to be wrong with, because a greedy solution that fails produces a plausible
 * answer rather than an error.
 *
 * Bands: name the idea, explain what has to hold for it to work, apply it to a described
 * problem, diagnose a greedy answer that is subtly wrong, and judge when an approximation is
 * acceptable.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That greedy needs a proof, not a feeling. "It looks right on my examples" is how students
 * fail this in interviews, because the counterexample is usually small and specific rather
 * than obvious. Several items are built around finding it.
 *
 * That the sort order IS the algorithm. Nearly every greedy solution is "sort by the right
 * thing, then take in order", and choosing what to sort by is where all the difficulty sits.
 *
 * And that greedy and [[dsa-dp]] are the same question answered differently: can I commit to
 * this choice, or must I try it and the alternatives? Recognising which applies is worth more
 * than knowing either technique.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

