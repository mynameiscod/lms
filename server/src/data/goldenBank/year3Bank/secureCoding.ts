/**
 * SECURE_CODING — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student writes code that is hard to misuse. [[web-security]] covers the named web
 * attacks and their defences; this covers the habits that stop a vulnerability existing in the
 * first place — how you handle input, secrets, errors, randomness and dependencies, in any
 * language and on any platform.
 *
 * Bands: name the habits, explain what each prevents, apply one to described code, diagnose a
 * risky implementation, and judge the calls where the secure option costs something.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That an interface should make the unsafe thing hard to write. A function that cannot be
 * called insecurely protects every future caller; a rule in a document protects nobody who has
 * not read it. Several D5 items turn on preferring the former.
 *
 * That secrets in source control are compromised the moment they are committed, and that
 * removing them later does not undo it. Rotation is the only real remedy, and students
 * consistently answer "delete the commit" instead.
 *
 * And that security-relevant randomness and comparison need the right primitives. A general
 * random number generator and a plain equality check are both correct-looking and both wrong,
 * which is what makes them worth measuring.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

