/**
 * REFACTORING — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can improve code they did not write without breaking it, and can tell that
 * activity apart from the several things people call by the same name. "Refactoring" in most
 * teams means "changing a lot of code and hoping", and the difference between that and the real
 * discipline is what this skill measures.
 *
 * Bands: name the moves, explain why behaviour must not change, apply a move to a described
 * mess, diagnose a refactor that went wrong, and judge when not to refactor at all.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That the defining constraint is unchanged behaviour. Adding a feature while restructuring is
 * not refactoring; it is two changes at once, and when it breaks nobody can say which half did
 * it. Several items turn on holding that line.
 *
 * That tests come first, not because tests are virtuous but because without them you cannot
 * know you preserved behaviour — and preserving behaviour is the entire definition.
 *
 * And that "make it worse first" is often correct. Inlining a bad abstraction before extracting
 * a good one is a real technique, and students trained to only ever tidy will not reach for it.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

