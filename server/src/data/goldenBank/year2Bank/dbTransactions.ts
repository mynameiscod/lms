/**
 * DB_TRANSACTIONS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can tell which operations must not be allowed to half-happen, and what
 * goes wrong when two of them run at once. Not whether they can expand ACID, which is the
 * thing every course asks and the thing that predicts least.
 *
 * Bands: name the parts, explain what each protects against, wrap an operation correctly,
 * diagnose a system already losing data to concurrency, and judge the cost of holding a
 * transaction open.
 *
 * ── THE POSITION THIS TAKES ───────────────────────────────────────────────────────────────
 *
 * That the hard part is not BEGIN and COMMIT but knowing where the boundary belongs, and that
 * most real transaction bugs are lost updates from read-modify-write in application code —
 * code that never looked wrong, because on one machine with one user it never was. Several
 * D4 and D5 items are about that pattern specifically.
 *
 * It also holds that a long transaction is a liability: it keeps locks, blocks others and
 * grows the work a rollback must undo, so network calls belong outside the boundary.
 */

