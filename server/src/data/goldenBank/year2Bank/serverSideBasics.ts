/**
 * SERVER_SIDE_BASICS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student understands what changes when code runs on a server rather than in one
 * person's browser. REST_APIS covers the shape of an endpoint; this is the ground underneath
 * it — request and response, statelessness, where state actually lives, and who the code is
 * running on behalf of.
 *
 * Bands: name the pieces, explain why a server forgets you between requests, build the usual
 * handlers, diagnose what goes wrong once there is more than one user or more than one
 * process, and judge the trade-offs a backend actually turns on.
 *
 * ── THE THREE POSITIONS THIS TAKES ────────────────────────────────────────────────────────
 *
 * That the server handles many people at once and remembers none of them. Nearly every
 * beginner backend bug is a browser habit applied to a server: a variable at module scope
 * holding "the current user", a value cached for everybody that was only true for one.
 *
 * That validation on the client is a convenience and never a control. The request is the
 * boundary, and anything past it can be forged — so a check the server does not repeat is a
 * check that does not exist.
 *
 * And that an error the caller can act on is part of the interface. Returning 200 with
 * `{ error: ... }`, or 500 for a bad postcode, forces every caller to parse prose to find out
 * what happened. D4 and D5 lean on both.
 */

