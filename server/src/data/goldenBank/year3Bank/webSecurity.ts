/**
 * WEB_SECURITY — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can recognise the standard web attacks in code they are reading, and knows
 * the actual defence rather than a superstition about one. [[authentication]] and
 * [[authorization]] cover who a request is from and what it may do; this covers everything that
 * goes wrong once the request is legitimate and the input is not.
 *
 * Bands: name the attacks, explain the mechanism, apply the right defence, diagnose vulnerable
 * code, and judge the calls where security trades against something else.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That injection of every kind is one bug: data being read as code. SQL injection, XSS and
 * command injection have the same shape and the same class of fix, and a student who sees the
 * pattern once can recognise the next variant in a language they have never used.
 *
 * That the fix is nearly always to keep data out of the parser rather than to clean it on the
 * way in. Blocklists and escaping-by-hand are the answers students give, and both lose to
 * somebody who tries harder. Parameterised queries and contextual encoding do not.
 *
 * And that validating input is not the same as encoding output. The same string is safe in one
 * place and dangerous in another, so the defence belongs where the data is used.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

