/**
 * DATA_WRANGLING — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can get a real dataset into a state worth analysing — and can say what
 * they did to it. PROBABILITY_STATISTICS is about what you conclude; this is everything before
 * that, which is where most of the time and nearly all of the silent mistakes live.
 *
 * Bands: name the operations, explain what each does to the data, apply them to a stated
 * problem, diagnose results that are wrong in ways that do not raise an error, and judge the
 * calls that have no correct answer.
 *
 * ── THE THREE POSITIONS THIS TAKES ────────────────────────────────────────────────────────
 *
 * That the dangerous errors are silent. A join that duplicates rows, a mean taken over nulls
 * dropped without noticing, a date parsed with the wrong day and month — none of these throw.
 * They produce a number, and the number is confidently wrong.
 *
 * That cleaning is a set of decisions, not a set of steps. Dropping rows with missing values
 * is a choice about who disappears from the analysis, and it is only defensible if you know
 * why they were missing.
 *
 * And that every transformation must be reproducible. A dataset cleaned by hand in a
 * spreadsheet cannot be checked, repeated or corrected, and nobody — including its author a
 * month later — can say what was done to it.
 */

