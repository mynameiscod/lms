/**
 * Golden Bank blueprint — Batch 3: version control and markup.
 *
 * GIT IS MEASURED AS STATE, NOT AS COMMANDS. A student who has memorised `git add` and `git
 * commit` and cannot say where a file currently is has learned nothing usable, and that is the
 * gap that makes beginners lose work. So the weight sits on the three states, on what each
 * command moves between them, and on diagnosing "my change is not there" — with commands named
 * only because you cannot discuss the states without them.
 *
 * HTML AND CSS ARE MEASURED AS OUTCOME, NOT AS VOCABULARY. Not "what does <em> mean" but "what
 * does this markup produce", "which rule wins", "why is this style not applied". Naming a
 * property is worth one recognition family; predicting what it does is worth the rest.
 *
 * BROWSER_FUNDAMENTALS EXISTS BECAUSE THE BROWSER IS WHERE FIRST-YEAR WEB WORK ACTUALLY BREAKS —
 * a stale cache, a blocked request, a change that is in the file and not on the screen. Every
 * family here is a thing a student will hit in their first month and misdiagnose.
 *
 * Markup, rules and command output appear inside the stem. All items stay mcq_single.
 */

