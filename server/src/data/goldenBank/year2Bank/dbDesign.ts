/**
 * DB_DESIGN — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can turn a description of a business into tables that will survive contact
 * with it. This sits deliberately above DB_NORMALIZATION: that skill is the rules, this one is
 * the modelling — what the entities are, what the keys should be, what the schema is allowed
 * to promise.
 *
 * Bands: name the pieces, explain relationships and keys, model a small domain, diagnose a
 * schema that is fighting its own application, and judge the decisions that cannot be undone.
 *
 * ── THE TWO POSITIONS THIS TAKES ──────────────────────────────────────────────────────────
 *
 * That the schema is where the rules belong. A constraint applies to every writer — the admin
 * screen, the import script, next year's migration — and a rule enforced only in application
 * code is a rule that holds until somebody writes a second code path. Several bands turn on it.
 *
 * And that the expensive mistakes are the ones about identity and time: choosing a natural key
 * that turns out to change, storing a local timestamp with no zone, deleting rather than
 * marking deleted. All three are cheap on day one and cost a migration afterwards, and that is
 * what D5 is built around.
 */

