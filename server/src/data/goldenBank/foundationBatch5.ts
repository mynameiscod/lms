/**
 * Golden Bank blueprint — Batch 5: data structures, databases and networks.
 *
 * DSA IS MEASURED AS COST AND BEHAVIOUR, NOT AS NOTATION. A first-year does not need to write
 * O-notation; they need to know that finding an item in an unsorted list means looking at all of
 * it, that inserting in the middle moves everything after it, and that a sorted list lets you
 * discard half at a time. Complexity is measured as "how much work", in words and counts.
 *
 * SQL IS MEASURED AS RESULT, NOT AS SYNTAX. Every family asks what a query returns, how many
 * rows, or which query answers a stated question. Clause order is measured once, because getting
 * it wrong stops the query running at all.
 *
 * DB_FUNDAMENTALS IS DELIBERATELY SEPARATE FROM SQL. Tables, keys, relationships and duplication
 * are design ideas that survive whichever language queries them, and a student who can write a
 * join but cannot say why the data was split into two tables has learned the syntax and missed
 * the subject.
 *
 * COMPUTER_NETWORKS IS MEASURED AT THE LEVEL A FIRST-YEAR CAN VERIFY — what a name resolves to,
 * why a request reaches one machine and not another, what a port distinguishes, and how to reason
 * about "it works for me and not for them".
 *
 * Tables, queries and data appear inside the stem. All items stay mcq_single.
 */

