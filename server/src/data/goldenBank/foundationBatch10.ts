/**
 * Golden Bank blueprint — Batch 10: forms, accessibility, the editor, and Python string literals.
 *
 * ── TWO OF THESE FOUR SIT NEXT TO A BANKED SKILL, AND ONE CONTRADICTS THE TAXONOMY ──
 *
 * HTML IS BANKED WITH THREE FAMILIES THAT BELONG HERE. HT_FAM09_FORM_BEHAVIOUR asks which values
 * a form submits; HT_FAM10_ALT_TEXT_BEHAVIOUR asks what alternative text an image should carry;
 * HT_FAM13_ACCESSIBILITY_REASONING asks what a screen reader user could not do. Those are one
 * family each of a skill that now has fifteen. The children are still justified — a form is
 * labels, types, grouping, validation and submission, and accessibility is keyboard reach, focus
 * order, heading structure and error reporting, none of which one family can carry — but the
 * parent should shed those three when it is next re-banked, and until then the cross-skill
 * duplicate check is what keeps the new questions off the old ground.
 *
 * PYTHON_STRINGS CONTRADICTS ITS OWN TAXONOMY ENTRY, AND THE ENTRY LOST. The taxonomy says this
 * is "the language one: indexing, slicing and the built-in methods" while DSA_STRINGS is "the
 * algorithmic node — palindromes, anagrams, two-pointer work". The bank disagrees: DSA_STRINGS
 * was authored as character position, length, comparison, range extraction, immutability, search,
 * split, join, whitespace, traversal, cost and edge behaviour. That is the language content,
 * banked under the algorithmic name, and it leaves the declared ground for PYTHON_STRINGS
 * entirely occupied.
 *
 * So this blueprint takes the one substantial area neither DSA_STRINGS nor PYTHON_BASICS touches:
 * literals and formatting. Quote forms, escapes, raw strings, triple quotes, interpolation, width
 * and precision, adjacent literals, and what happens to a non-text value placed inside a literal.
 * Not one of those appears in any banked family. It is a narrower skill than the taxonomy
 * describes and it is a real one, and the alternative — writing fifteen families that re-ask
 * DSA_STRINGS in Python costume — is exactly the wording-variant failure this whole design
 * exists to prevent. If the decision is instead to retire the node, this file is the only thing
 * that has to be deleted.
 *
 * IDE_PROFICIENCY IS NOT DEBUGGING AND IS NOT A PRODUCT TOUR. It would collapse into DEBUGGING if
 * it asked how to find a fault, and it would date within a year if it asked where a menu item
 * lives. What it measures instead is what the tool is telling you and how far that can be
 * trusted: what a search covered, what a rename reached, which directory the terminal started in,
 * what an editor warning is and is not evidence of, and what the absence of a warning proves.
 * Every stem describes a capability rather than naming an editor.
 */

