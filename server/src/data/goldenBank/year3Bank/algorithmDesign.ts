/**
 * ALGORITHM_DESIGN — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can get from a problem statement to an approach. Every other algorithms
 * skill in this bank measures one technique; this measures the step before choosing one —
 * understanding the problem, recognising its shape, picking a strategy, and knowing what the
 * choice will cost.
 *
 * Bands: name the strategies and what they are for, explain how the constraints point at an
 * approach, apply that to a described problem, diagnose an approach that was chosen wrongly,
 * and judge the trade-offs that have no textbook answer.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That the input size tells you the complexity you are allowed, and the allowed complexity
 * narrows the technique enormously. n up to a million rules out anything quadratic; n up to
 * twenty invites exponential search. This is the single most useful habit in the file.
 *
 * That understanding the problem precedes everything, and that the commonest failure in an
 * interview is solving a problem nobody asked about. Restating it and naming the edge cases
 * costs a minute and saves the whole question.
 *
 * And that a correct slow solution beats a fast wrong one, and is usually the route to the
 * fast right one. Brute force first is a technique, not a concession.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

