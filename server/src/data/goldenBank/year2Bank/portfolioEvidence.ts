/**
 * PORTFOLIO_EVIDENCE — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Not whether the student has a portfolio. Whether they can tell what counts as evidence to
 * somebody who has ninety seconds and no reason to believe them.
 *
 * That is a judgement, and judgement can be measured. What cannot be measured by a multiple
 * choice paper is whether they actually built anything — the applied evidence track does that,
 * and this bank does not pretend to. What it asks is: shown two projects, two READMEs, two
 * commit histories, can this student say which one a reviewer will believe, and why.
 *
 * ── THE THREE POSITIONS THIS TAKES ────────────────────────────────────────────────────────
 *
 * That a reviewer is looking for reasons to stop reading. Every item they cannot verify quickly
 * is a reason. This is why a dead demo link costs more than a missing one.
 *
 * That evidence beats claims, and specific beats impressive. "Built a full-stack e-commerce
 * platform" is a claim; a running link and a commit history are evidence. Four tutorial projects
 * are worth less than one that solved a problem the student actually had.
 *
 * And that the portfolio is read by someone deciding whether to spend an hour interviewing you.
 * That frame decides nearly every item here — what to include, what to cut, what to explain.
 */

