/**
 * ML_WORKFLOW — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can run a machine learning project without fooling themselves. Not the
 * mathematics of any particular model — the process: framing the problem, splitting the data,
 * choosing a metric that means something, and knowing when a good number is a lie.
 *
 * This is the AI/ML direction's backbone skill, and it is deliberately about method rather
 * than algorithms, because a student who can evaluate honestly can learn any model, and one
 * who cannot will ship a broken one confidently.
 *
 * Bands: name the pieces, explain why the discipline exists, apply it to a described project,
 * diagnose a result that cannot be trusted, and judge whether the thing should be built at all.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That leakage is the defining failure. A model that saw the answer during training scores
 * beautifully and is worthless, and the student will not notice unless they are looking. Four
 * items at D4 are different disguises of the same mistake.
 *
 * That accuracy is usually the wrong metric, because the interesting cases are rare. Ninety-
 * nine percent accuracy on a one-percent problem is achieved by predicting "no" every time.
 *
 * And that most of the work is data, not modelling. Students expect to spend their time on the
 * model and spend it on the data, and knowing that in advance is worth a term of disappointment.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

