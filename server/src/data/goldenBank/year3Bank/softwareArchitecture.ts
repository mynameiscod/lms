/**
 * SOFTWARE_ARCHITECTURE — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can place a boundary and defend it. Not whether they can recite layer names
 * or draw a diagram with the right number of boxes — an architecture is a set of decisions about
 * what may depend on what, and the skill is making those decisions and living with them.
 *
 * Bands: name the layers, explain what a boundary buys, place one in a described system,
 * diagnose an architecture that has gone wrong, and judge the calls that have no rule.
 *
 * ── THE THREE POSITIONS THIS TAKES ────────────────────────────────────────────────────────
 *
 * That architecture is about DEPENDENCY DIRECTION above all else. Which way the arrows point
 * decides what you can test, replace and understand alone; almost every item here reduces to it.
 *
 * That the decisions worth labouring over are the ones that are expensive to reverse. Choosing a
 * library is cheap to undo; letting the domain import the database is not, and a student who can
 * tell those apart will spend their effort in the right place.
 *
 * And that every layer has a cost. An abstraction is a thing the next reader must hold in their
 * head, so "add a layer" is never free and several items turn on saying what it bought.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * The four options in each item are written to similar lengths on purpose. The bank's own suite
 * fails a file where correct answers run long, because a student can then score above chance by
 * picking the longest option without reading the question — which measures test-taking rather
 * than architecture.
 */

