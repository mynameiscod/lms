/**
 * DSA_GRAPHS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can recognise a graph problem when it is not described as one, and then
 * pick the traversal that answers it. Most interview graph questions arrive dressed as
 * something else — a grid, a set of prerequisites, a list of friendships, a network of pipes —
 * and the skill is the translation as much as the algorithm.
 *
 * Bands: name the parts, explain what each traversal guarantees, apply one to a described
 * problem, diagnose a traversal that gives the wrong answer or never stops, and judge the
 * choices between algorithms that both work.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That the visited set is the algorithm, not an optimisation. Almost every broken traversal a
 * student writes is one that forgot it, and the failure is an infinite loop rather than a wrong
 * answer, so several items make that the thing being tested.
 *
 * That breadth-first gives the fewest EDGES, which is only the shortest path when every edge
 * costs the same. The moment weights differ it is the wrong tool, and students carry that
 * mistake a long way.
 *
 * And that the representation is a decision with consequences. An adjacency matrix on a sparse
 * graph is the difference between a solution that runs and one that does not.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * The four options are written to similar lengths deliberately; the suite fails a bank where
 * correct answers run long, since that lets a student score without reading the question.
 */

