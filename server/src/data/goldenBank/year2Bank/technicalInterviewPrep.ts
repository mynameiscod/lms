/**
 * TECHNICAL_INTERVIEW_PREP — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student understands what an interviewer is actually measuring, and can behave
 * accordingly under pressure. Not whether they have memorised solutions, which is the thing
 * most preparation optimises for and the thing that fails first when the question is unfamiliar.
 *
 * Bands: name the formats, explain what each is testing, apply the right behaviour in a given
 * moment, diagnose an interview that went wrong, and judge how to prepare.
 *
 * ── THE TWO POSITIONS THIS TAKES ──────────────────────────────────────────────────────────
 *
 * That the interviewer is hiring a colleague, not a solution. They are asking what it is like
 * to work through a problem with you — which is why silence is the costliest mistake, why a
 * clarifying question scores, and why "I don't know, here is how I would find out" is a strong
 * answer rather than a lost one. Most bands rest on that.
 *
 * And that preparation should be honest. An inflated CV produces questions you cannot answer,
 * a memorised solution collapses on the follow-up, and a candidate who has genuinely built
 * something has an advantage that no amount of practice questions replaces. D5 is built on it.
 */

