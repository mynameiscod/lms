/**
 * DESIGN_PATTERNS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can RECOGNISE a shape in code they did not write, and — more importantly —
 * whether they know when not to reach for one. Naming the twenty-three Gang of Four patterns is
 * not the skill and is not asked for anywhere here.
 *
 * Bands: name what a pattern is, explain what each one buys, apply one to a described problem,
 * diagnose a codebase where patterns have gone wrong, and judge whether one is worth its weight.
 *
 * ── THE THREE POSITIONS THIS TAKES ────────────────────────────────────────────────────────
 *
 * That a pattern is a NAME for something that already keeps happening, not a thing to go
 * looking for. Code arrives at strategy on its own; the name is what lets two engineers discuss
 * it in one word.
 *
 * That the commonest mistake with patterns is using one. A factory in front of a constructor
 * that will only ever build one thing is machinery a reader has to hold with nothing to show
 * for it, and several items turn on spotting exactly that.
 *
 * And that patterns are about what can CHANGE independently. Strategy exists because the
 * algorithm changes and the caller does not; observer exists because the listeners change and
 * the thing being listened to does not. A student who has that can derive the rest.
 */

