/**
 * Golden Bank blueprint — Batch 8: AI Literacy.
 *
 * The second module the Year-1 audit found with nothing to map to. It is also the module most at
 * risk of measuring opinion, of dating within a year, and of quietly becoming a different skill
 * that is already banked. Four decisions were taken before any family was written.
 *
 * NOTHING HERE DEPENDS ON WHICH PRODUCT IS CURRENTLY BEST. No family names a vendor, a model or a
 * version, and no correct answer would change if the whole market were replaced tomorrow. What is
 * measured is the mechanism and the reasoning that follows from it: that output is produced a
 * token at a time, that a conversation does not train anything, that a fluent sentence carries no
 * evidence about its own truth. Those hold across products because they are properties of how the
 * systems work rather than of who sells them.
 *
 * AI_ASSISTED_CODING IS NOT DEBUGGING AND NOT CLEAN_CODE, and without care it would become both.
 * The banked DEBUGGING skill measures method — what would reproduce this, which hypothesis the
 * evidence supports. Judging whether code is well written belongs to CLEAN_CODE. So this skill
 * measures the one thing neither can: verifying a claim you did not write. Does the code do what
 * was actually asked, does the call it uses exist, what did it assume without saying, which test
 * would expose the doubt, and what does a passing run actually establish. Every stem hands the
 * student code they did not author and a reason to doubt it.
 *
 * PROMPT_ENGINEERING IS MADE MEASURABLE BY ASKING ABOUT DEFECTS RATHER THAN QUALITY. "Which prompt
 * is better" is a taste question with four defensible answers. "Which of these prompts could be
 * satisfied in two different ways", "which part of this prompt caused that output", "which single
 * change would test the hypothesis" — each has one answer a reader can verify from the text. Any
 * family that could only be settled by preference was not written.
 *
 * AI_RESPONSIBLE_USE IS ABOUT CONSEQUENCES THAT CAN BE TRACED, not about conduct that can be
 * preached. Not "should you use these tools" but "which of these claims needs a source before it
 * is published", "what follows once this data has been pasted in", "who is disadvantaged when
 * this output is wrong". Advice would date and would be unmeasurable; the reasoning about
 * consequence does neither.
 */

