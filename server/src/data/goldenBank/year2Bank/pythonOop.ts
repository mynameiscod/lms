/**
 * PYTHON_OOP — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can write Python classes the way Python wants them written. This is not
 * OOP_CONCEPTS in Python syntax — that skill covers what a class is for, and this one covers
 * what Python specifically does differently, because most of the bugs live in the difference.
 *
 * Bands: name the constructs, explain what Python does that other languages do not, write a
 * class correctly, diagnose the specific traps, and judge when a class is the wrong answer in
 * a language with first-class functions and dictionaries.
 *
 * ── THE TWO POSITIONS THIS TAKES ──────────────────────────────────────────────────────────
 *
 * That Python's privacy is a convention and nothing more. A single underscore asks politely, a
 * double underscore mangles the name to avoid collisions, and neither prevents anything. A
 * student who believes `__x` is private has been taught Java with Python syntax, and D4 has an
 * item on exactly that.
 *
 * And that the mutable default argument is the trap worth building a band around. `def f(x=[])`
 * evaluates that list ONCE, at definition, so every call shares it. It looks correct, passes
 * review, and produces a bug that arrives days later — which is precisely the profile this
 * bank is meant to measure.
 */

