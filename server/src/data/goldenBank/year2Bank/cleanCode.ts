/**
 * CLEAN_CODE — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can tell the difference between code that is tidy and code that is easy to
 * change. Not whether they can recite rules about function length, which is the version of this
 * subject that gets taught and the version that produces six-line functions calling six-line
 * functions for no gain.
 *
 * Bands: name the ideas, explain what each is for, apply them to a specific piece of code,
 * diagnose a codebase that has become expensive to work in, and judge when a rule should be
 * broken.
 *
 * ── THE TWO POSITIONS THIS TAKES ──────────────────────────────────────────────────────────
 *
 * That naming is the highest-leverage thing in the subject. A good name removes the need for a
 * comment, makes a wrong call look wrong, and is the one improvement that never makes anything
 * else worse. Several bands lean on it.
 *
 * And that every rule here is a heuristic with a purpose, so the purpose outranks the rule. A
 * function is too long when it is hard to follow, not at twenty lines; a comment is bad when it
 * restates the code, not because comments are bad. D5 is built on knowing which rule is serving
 * what, because a rule applied without its reason produces its own kind of mess.
 */

