/**
 * CODE_REVIEW — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can read somebody else's change and say something useful about it. CLEAN_CODE
 * is about writing; this is about reading, and about the part nobody teaches — that a review is a
 * conversation between two people, and half of it is how the comment is worded.
 *
 * Bands: name the mechanics, explain what a review is for, review a described change, diagnose
 * the ways review processes fail, and judge the calls that have no rule.
 *
 * ── THE THREE POSITIONS THIS TAKES ────────────────────────────────────────────────────────
 *
 * That the first duty of a reviewer is to understand the change, not to find fault with it. A
 * review that starts by hunting for something to say produces style comments on a change that
 * breaks a business rule nobody read carefully enough to notice.
 *
 * That the size of the change decides the quality of the review. Nobody meaningfully reviews
 * two thousand lines; they skim and approve. Most review failures are really batching failures.
 *
 * And that how a comment is written changes whether it is acted on. "This is wrong" and "what
 * happens here if the list is empty?" can point at the same defect, and only one of them
 * reliably gets it fixed. Several bands turn on that.
 */

