/**
 * ERROR_HANDLING_DESIGN — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student decides deliberately what happens when something fails, rather than
 * discovering it in production. Most students learn try/catch as syntax; this is the level
 * above — which failures are expected, who is responsible for handling each one, and what the
 * caller is entitled to know.
 *
 * Bands: name the pieces, explain why the conventions exist, apply them to described code,
 * diagnose error handling that has made things worse, and judge the calls with no rule.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That a swallowed error is worse than a crash. A crash is loud and traceable; a caught
 * exception that logs nothing and continues turns one failure into corrupted state discovered
 * a week later by somebody who cannot find the cause. Several items exist to make that concrete.
 *
 * That expected failures are not exceptional. A user typing a bad email is the normal
 * operation of a form, and modelling it as an exception makes the ordinary path harder to read
 * than the rare one.
 *
 * And that an error must carry what the handler needs to act. "Something went wrong" is a
 * message that costs somebody an hour, and the cost is paid every single time it appears.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

