/**
 * DEPLOYMENT — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can get a change in front of users without breaking anything, and can say
 * what to do when it does break. [[ci-cd]] covers the pipeline that produces and promotes a
 * build; this covers the release itself — the strategy, the moment of cutover, and the recovery.
 *
 * Bands: name the strategies, explain what each buys, apply one to a described release,
 * diagnose a deployment that went wrong, and judge the calls that depend on context.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That during any rollout, two versions of the code are live at once. Almost every genuinely
 * nasty deployment bug follows from forgetting that — the dropped column, the changed message
 * format, the session the other version cannot read. It appears at four bands.
 *
 * That the schema and the code must be decoupled, because they cannot be deployed atomically.
 * Expand, migrate, contract is the answer and it is three releases, not one.
 *
 * And that recovery time matters more than failure rate. You cannot drive the chance of a bad
 * release to zero; you can make a bad release cost two minutes, and that is the lever.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

