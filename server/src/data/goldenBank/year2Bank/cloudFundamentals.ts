/**
 * CLOUD_FUNDAMENTALS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can reason about running software on machines they do not own. Not which
 * buttons a particular provider puts where — that changes and is looked up — but the ideas
 * every provider is a version of: what you rent, what you are billed for, what fails, and what
 * you are still responsible for after you have paid somebody else to run it.
 *
 * Bands: name the pieces, explain what each model actually buys, choose one for a requirement,
 * diagnose the bills and outages that surprise people, and judge the trade-offs honestly.
 *
 * ── THE THREE POSITIONS THIS TAKES ────────────────────────────────────────────────────────
 *
 * That the cloud is somebody else's computer, rented by the hour, and nearly every surprise
 * follows from taking that literally. A server you forgot is a server you are paying for. A
 * disk that lives inside an instance dies with the instance.
 *
 * That renting does not transfer responsibility, only operation. The provider secures the
 * building and the hypervisor; your open storage bucket and your leaked key are still yours.
 * The shared responsibility model is the single most load-bearing idea here.
 *
 * And that "it scales" is a claim about elasticity, not about your code. Ten instances of a
 * service that writes to one small database is ten times the pressure on the bottleneck. D4
 * and D5 lean on that repeatedly.
 */

