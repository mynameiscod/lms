/**
 * COMMUNICATION — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can work with other people on a technical problem. [[technical-writing]]
 * covers the written artefact; this covers the live exchange — explaining, disagreeing, asking
 * for help, giving and taking review, and saying that something is going wrong before it has.
 *
 * Bands: name the practices, explain why they work, apply them to a described situation,
 * diagnose an exchange that has gone badly, and judge the genuinely contested calls.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That you adjust to the listener, not to your own understanding. The same fact told to an
 * engineer, a manager and a customer is three different sentences, and choosing the wrong one
 * is the most common failure here.
 *
 * That bad news travels best early and plainly. Nearly every disaster in a project was known
 * to somebody weeks before it was said out loud, and the delay is what made it a disaster.
 *
 * And that disagreement is a technical activity with a method: establish what you both want,
 * separate fact from preference, and say what would change your mind. Arguing harder is not
 * a method.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

