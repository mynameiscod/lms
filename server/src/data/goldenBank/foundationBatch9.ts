/**
 * Golden Bank blueprint — Batch 9: processes, memory, files and the shell.
 *
 * ── THE PARENT SKILL ALREADY OWNS SOME OF THIS GROUND, AND THAT HAS TO BE SAID PLAINLY ──
 *
 * OPERATING_SYSTEMS is banked with sixteen families and fifty approved questions, and six of
 * those families sit on ground these five skills were created for:
 *
 *   OS_FAM03_PROCESS_COMPARISON       how many processes exist, and what each has of its own
 *   OS_FAM15_PROCESS_TERM_RECOGNITION program, process and application as terms
 *   OS_FAM06_MEMORY_ISOLATION         what a process can reach, and what happens when it ends
 *   OS_FAM07_PATH_REASONING           what a path refers to
 *   OS_FAM16_FILE_VS_DIRECTORY        which described items are files and which directories
 *   OS_FAM10_PRIVILEGE_BOUNDARY       whether an action needs the kernel
 *
 * The audit that created these five skills tested them against the taxonomy — is each half
 * separately measurable — and did not test them against the bank. So the split is sound in
 * principle and overlapping in practice, and pretending otherwise would produce a hundred and
 * fifty questions that quietly re-ask what students have already been asked.
 *
 * WHAT IS DONE ABOUT IT HERE. Every family below is pitched past where the parent stops. The
 * parent asks what a process is; OS_PROCESSES asks what happens to it across its life — states,
 * parents and children, what a stop request actually does, what an identifier means once it has
 * been reused. The parent asks what memory a process can reach; OS_MEMORY asks where a particular
 * value lives, what happens when the stack grows without bound, and what memory pressure looks
 * like from outside. The parent asks what a path refers to; FILE_SYSTEMS_PERMISSIONS asks how a
 * relative path resolves from a stated directory, and what the three permission bits actually
 * permit — including the one nobody expects, which is that deleting a file is governed by its
 * directory rather than by the file.
 *
 * WHAT IS NOT DONE HERE, AND SHOULD BE. The parent should shed those six families and re-bank
 * the vacated allocation on the ground only it covers: what an operating system is for,
 * scheduling, contended resources, privilege, startup, and resource exhaustion. That is a change
 * to fifty approved questions and is not smuggled into a blueprint commit. Until it happens, the
 * cross-skill duplicate check at authoring time is the backstop, and it is a real one — it
 * compares every new question against every banked one and fails the build on a near match.
 *
 * SHELL_COMMANDS AND SHELL_PIPELINES DIVIDE CLEANLY AND ARE KEPT THAT WAY. One is about issuing a
 * command — what it does, what it takes, what it destroys. The other is about composing several,
 * where the whole subject is what flows between them. No family in the first mentions a pipe, and
 * no family in the second turns on what any individual command does.
 *
 * NO STEM NAMES A DISTRIBUTION OR A SHELL. Commands are described by what they do rather than
 * spelled, because a question that rewards recalling a flag measures memory of a manual page.
 */

