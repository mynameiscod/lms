import { LearningUnitType, LearningUnitCategory } from '../../models/CurriculumLearningUnit';

/**
 * The Year-1 mega curriculum, as a dataset.
 *
 * ── WHAT THIS IS ──────────────────────────────────────────────────────────────────────────
 *
 * Thirty-nine broad curriculum topics decomposed into the units they actually teach. It is DATA,
 * not a migration: nothing here runs, and importing it is a separate deliberate act that can be
 * validated first and re-run safely.
 *
 * ── WHY DECOMPOSITION IS THE WHOLE JOB ────────────────────────────────────────────────────
 *
 * "Object-Oriented Programming" is a good topic and a hopeless day. While the topic was the
 * smallest node, thirty-nine topics could only produce thirty-nine sessions, and a student who
 * bought ninety days opened a twenty-eight-day plan. The fix is not a longer calendar, it is a
 * finer unit.
 *
 * SO NO UNIT IS NAMED "BASICS". A unit called "Python Basics" is the same failure one level down:
 * it hides four lessons behind one title and nothing can schedule it sensibly. Every unit here is
 * one sitting's worth of one idea, and the validator refuses the dataset if a placeholder name
 * creeps back in.
 *
 * ── WHAT IT DELIBERATELY DOES NOT CONTAIN ─────────────────────────────────────────────────
 *
 * No day numbers. A unit belongs to the master curriculum; which day a student meets it is
 * decided per student, later, by the composer. There are more units here than any ninety-day plan
 * can hold, and that is the point: a pool larger than the plan is what makes selection possible.
 *
 * ── SOURCE MATERIAL ───────────────────────────────────────────────────────────────────────
 *
 * Module codes, topic codes, skill keys, prerequisite skills, directions and default depth come
 * from the Year-1 curriculum itself and are INHERITED rather than restated — a unit that retyped
 * its topic's skills would drift the moment the curriculum was edited. Only what is genuinely
 * per-unit lives here: the sequence, the titles, the outcomes and the shape of the work.
 */

export interface UnitSeed {
  /** Appended to the topic code to make the unit code. Stable; renaming the title never moves it. */
  slug: string;
  title: string;
  description: string;
  learningOutcomes: string[];
  estimatedMinutes: number;
  unitType?: LearningUnitType;
  /** Sibling slugs that must be taught first. Resolved to full unit codes on import. */
  after?: string[];
  /** Narrows the topic's skills. Omitted means the unit teaches all of them. */
  skillKeys?: string[];
}

export interface TopicSeed {
  category: LearningUnitCategory;
  units: UnitSeed[];
}

/** Compact constructor, so the dataset below reads as a syllabus rather than as JSON. */
const u = (
  slug: string, title: string, description: string,
  learningOutcomes: string[], estimatedMinutes: number,
  extra: Partial<UnitSeed> = {},
): UnitSeed => ({ slug, title, description, learningOutcomes, estimatedMinutes, ...extra });

/** A topic's last three units, in the shape every topic ends with. */
const debugPractiseBuild = (
  what: string, debugMin = 45, practiceMin = 60, projectMin = 120,
): UnitSeed[] => [
  u('DEBUGGING', `Debugging ${what}`,
    `Reading the errors ${what.toLowerCase()} produces, and finding the cause rather than guessing.`,
    [`Diagnose a broken ${what.toLowerCase()} example without changing it at random`],
    debugMin, { unitType: 'DEBUG', after: [] }),
  u('PRACTICE', `${what} Practice`,
    `Enough repetition that ${what.toLowerCase()} stops needing thought.`,
    [`Work ${what.toLowerCase()} problems without looking things up`],
    practiceMin, { unitType: 'PRACTICE', after: ['DEBUGGING'] }),
  u('MINI_PROJECT', `Mini Project — ${what}`,
    'One small thing built end to end, and explained afterwards.',
    ['Build and describe something that uses what this topic taught'],
    projectMin, { unitType: 'PROJECT', after: ['PRACTICE'] }),
];

/**
 * Re-point the prerequisites of chosen units in a generated tail, by slug.
 *
 * `debugPractiseBuild` gives every topic the same shape — debugging after nothing, practice after
 * debugging — and that shape is wrong wherever a topic's debugging exercise uses what its lessons
 * taught. Stated per topic here rather than by changing the helper's defaults, so one topic's
 * authoring decision cannot silently move another's.
 */
const afterFor = (units: UnitSeed[], after: Record<string, string[]>): UnitSeed[] =>
  units.map(x => (after[x.slug] ? { ...x, after: after[x.slug] } : x));

