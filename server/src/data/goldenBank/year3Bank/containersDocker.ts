/**
 * CONTAINERS_DOCKER — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student understands what a container actually is, and can therefore predict how one
 * behaves. Most students learn Docker as a list of commands, which works until something is
 * wrong — and then the difference between a container and a virtual machine, or between an
 * image and a container, is exactly what they need and do not have.
 *
 * Bands: name the parts, explain why containers behave as they do, apply that to building and
 * running one, diagnose a container that will not work, and judge where containers help and
 * where they are ceremony.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That a container is a process, not a small machine. Nearly every surprising behaviour —
 * why it exits immediately, why there is no init system, why killing PID 1 stops everything —
 * follows from that single sentence, and students who hold the virtual-machine model get all
 * of them wrong.
 *
 * That the image is a template and the container is a running instance of it, and that anything
 * written inside a container dies with it. Persistence is a deliberate act.
 *
 * And that layer order in a Dockerfile is a caching decision. Copying source before installing
 * dependencies rebuilds the world on every edit, and it is the most common real Dockerfile
 * mistake rather than a matter of taste.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

