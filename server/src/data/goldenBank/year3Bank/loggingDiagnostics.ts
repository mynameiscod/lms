/**
 * LOGGING_DIAGNOSTICS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can write logs that answer a question at three in the morning. Everyone
 * can call a log function; the skill is deciding what to record, at what level, with what
 * attached, so that the log is useful to somebody who was not there and does not have the code
 * in front of them.
 *
 * Bands: name the pieces, explain what makes a log useful, apply that to described code,
 * diagnose logging that has failed its purpose, and judge the trade-offs against cost,
 * privacy and noise.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That the reader is a stranger under pressure. Every rule here — include the identifiers,
 * say what you were doing, log the outcome not the intention — follows from picturing somebody
 * who has never seen this code trying to work out what happened.
 *
 * That a log without a correlation id is nearly useless in any system with concurrency,
 * because the lines from one request are interleaved with a hundred others. This appears at
 * three bands because students consistently underrate it.
 *
 * And that logging is an output with a cost — money, disk, and attention. A log nobody can
 * search and a log everybody ignores have the same value, which is none.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

