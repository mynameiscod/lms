/**
 * Golden Bank blueprint — Batch 7: Mathematics for Computer Science.
 *
 * These seven skills exist because the Year-1 audit found a whole module with nothing to map to.
 * That is also what makes them the most dangerous batch to author: every one of them borders a
 * skill that is already banked, and a family written without care would measure the neighbour.
 * Three boundaries had to be settled before a single family was written.
 *
 * PROPOSITIONAL_LOGIC IS NOT APTITUDE_REASONING_LOGIC. The banked reasoning skill is about
 * natural-language claims — all and some, what follows from two statements, which step is not
 * warranted. This one is truth-functional: the value of a compound under stated values, when an
 * implication is false, whether two expressions share a table. The test that keeps them apart is
 * that nothing here can be answered by reading a sentence carefully, and nothing there can be
 * answered by filling in a table. A student may be strong at one and weak at the other, which is
 * the whole reason both are measured.
 *
 * BOOLEAN_ALGEBRA IS NOT PROPOSITIONAL_LOGIC EITHER, and this is the finer of the two lines.
 * Logic asks what a compound is worth; algebra asks what it can be rewritten as. Evaluation
 * families belong to logic, law and simplification families to algebra, and the one place they
 * genuinely meet — De Morgan — is deliberately written twice from different ends: logic negates a
 * condition and asks which branch now runs, algebra pushes a bar through a product and asks which
 * form is equivalent. If those two ever read alike, one of them is wrong.
 *
 * PROBABILITY_STATISTICS IS NOT APTITUDE_DATA_INTERPRETATION. Data interpretation reads a chart
 * or a table and extracts a value; this reads no charts at all. It is sample spaces, the rules
 * that combine events, and what a summary number does and does not tell you — which is why its
 * strongest families are the ones where the arithmetic is easy and the reasoning is not.
 *
 * SET_THEORY DOES NOT REPEAT DE MORGAN. It would have been the obvious thirteenth family, and it
 * was dropped precisely because two other skills in this same batch carry it. What replaced it is
 * better anyway: deciding whether a stated identity holds for ALL sets, which is answered by
 * producing a counterexample and cannot be answered by recalling a law.
 *
 * THE ARITHMETIC IS KEPT SMALL EVERYWHERE. Four-bit numbers, three-element sets, two-by-two
 * matrices, six-sided dice. A student who cannot multiply two four-digit numbers in their head is
 * not the student this module is failing to reach, and every question whose difficulty came from
 * its arithmetic rather than its reasoning was rewritten until it did not.
 *
 * All seven follow the fifteen-family template, so their allocation is derived rather than
 * hand-written — see foundationAllocation.templatedAllocation.
 */

