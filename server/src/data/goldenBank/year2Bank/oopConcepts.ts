/**
 * OOP_CONCEPTS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can say what a class is FOR, and recognise when objects are making a design
 * worse. Not whether they can recite the four pillars, which is the single most memorised and
 * least understood answer in this subject.
 *
 * Bands: name the ideas, explain what each buys, apply them to a small design, diagnose a class
 * hierarchy that has gone wrong, and judge when not to use inheritance at all.
 *
 * ── THE TWO POSITIONS THIS TAKES ──────────────────────────────────────────────────────────
 *
 * That encapsulation is the pillar that actually pays. An object whose invariants cannot be
 * broken from outside is worth more than any amount of hierarchy, and most of the value people
 * attribute to OOP comes from this one idea.
 *
 * And that inheritance is over-used and usually wrong. It is the tightest coupling a language
 * offers, it is reached for to share code when composition would do, and a hierarchy built
 * around what things ARE breaks the moment the real world disagrees. D4 and D5 are built on
 * that: the square that is not a rectangle, the base class nobody can change, the four-level
 * tree where the behaviour lives three levels up.
 */

