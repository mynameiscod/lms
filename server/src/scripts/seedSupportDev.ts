/**
 * Help & Support — DEVELOPMENT AND TEST DATA ONLY. Refuses to run in production.
 *
 *   npx ts-node src/scripts/seedSupportDev.ts <tenantId> [--tickets N]
 *
 * Creates:
 *   - an empty SupportConfiguration for the tenant (every target blank, as in production);
 *   - with --tickets, N sample tickets raised by that tenant's students, marked "[DEV SAMPLE]"
 *     in the subject so they can never be mistaken for real ones, with a public reply on some.
 *
 * It writes no FAQ content: Phase 4 seeds placeholder structure, and nothing here should read
 * like a real answer about features, fees or response times.
 */
import dotenv from 'dotenv';
import mongoose from 'mongoose';
import User from '../models/User';
import SupportTicket from '../models/SupportTicket';
import SupportMessage from '../models/SupportMessage';
import SupportConfiguration from '../models/SupportConfiguration';
import { nextTicketNumber } from '../services/supportTicketNumber';
import { SUPPORT_MODULES, TICKET_CATEGORIES, TICKET_PRIORITIES, TICKET_STATUSES } from '../data/supportPolicy';

dotenv.config();

export const DEV_SAMPLE_MARK = '[DEV SAMPLE]';

export function assertNotProduction(env = process.env) {
  const uri = String(env.MONGODB_URI || env.MONGO_URI || '');
  if (env.NODE_ENV === 'production' || env.ALLOW_SUPPORT_SEED === 'never') throw new Error('seedSupportDev refuses to run in production.');
  if (/mongodb\+srv:\/\//.test(uri) && env.ALLOW_SUPPORT_SEED !== 'yes') {
    throw new Error('This looks like a hosted database. Set ALLOW_SUPPORT_SEED=yes if it really is a development one.');
  }
}

export async function seedSupport(tenantId: string, tickets: number): Promise<{ config: boolean; tickets: number }> {
  const had = await SupportConfiguration.exists({ tenantId });
  if (!had) await SupportConfiguration.create({ tenantId });
  if (!tickets) return { config: !had, tickets: 0 };

  const students = await User.find({ tenantId, role: 'STUDENT' }).select('_id role').limit(20).lean();
  if (!students.length) throw new Error('No students in this tenant to raise sample tickets.');

  let made = 0;
  for (let i = 0; i < tickets; i++) {
    const who: any = students[i % students.length];
    const status = TICKET_STATUSES[i % TICKET_STATUSES.length];
    const t = await SupportTicket.create({
      tenantId,
      ticketNumber: await nextTicketNumber(),
      requesterId: who._id,
      requesterRole: who.role,
      subject: `${DEV_SAMPLE_MARK} Sample ticket ${i + 1}`,
      description: 'Generated by seedSupportDev for development and tests.',
      module: SUPPORT_MODULES[i % SUPPORT_MODULES.length],
      category: TICKET_CATEGORIES[i % TICKET_CATEGORIES.length],
      priority: TICKET_PRIORITIES[i % TICKET_PRIORITIES.length],
      status,
      resolvedAt: status === 'resolved' || status === 'closed' ? new Date() : null,
      closedAt: status === 'closed' ? new Date() : null,
    });
    if (i % 2 === 0) {
      await SupportMessage.create({ tenantId, ticketId: t._id, authorKind: 'system', visibility: 'public', body: `${DEV_SAMPLE_MARK} Sample reply.` });
    }
    made++;
  }
  return { config: !had, tickets: made };
}

async function main() {
  assertNotProduction();
  const tenantId = process.argv[2];
  const at = process.argv.indexOf('--tickets');
  const tickets = at > -1 ? Math.min(200, Math.max(0, Number(process.argv[at + 1]) || 0)) : 0;
  if (!tenantId || !mongoose.isValidObjectId(tenantId)) {
    console.error('Usage: seedSupportDev.ts <tenantId> [--tickets N]');
    process.exit(1);
  }
  await mongoose.connect(process.env.MONGODB_URI || process.env.MONGO_URI || '');
  const r = await seedSupport(tenantId, tickets);
  console.log(`configuration ${r.config ? 'created (empty)' : 'already there'}; sample tickets ${r.tickets}`);
  await mongoose.disconnect();
}

if (require.main === module) {
  main().catch(async (e) => { console.error('FAILED', e?.message || e); await mongoose.disconnect(); process.exit(1); });
}
