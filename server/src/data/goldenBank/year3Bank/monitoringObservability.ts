/**
 * MONITORING_OBSERVABILITY — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can tell whether a running system is healthy, and find out why when it is
 * not. [[logging-diagnostics]] covers the individual record of what happened; this covers the
 * aggregate view — what to measure, what to alert on, and how to ask a question of a system
 * you did not anticipate needing to ask.
 *
 * Bands: name the pieces, explain why the conventions exist, apply them to a described
 * service, diagnose monitoring that is failing its job, and judge what is worth watching.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That you alert on symptoms users feel, not on causes. High CPU is not a problem; checkout
 * failing is. Alerting on causes produces pages for things nobody would have noticed and
 * misses the outages caused by something you never thought to watch.
 *
 * That an average hides everything that matters. The mean response time is fine while the
 * slowest 1% of users cannot use the product at all, and percentiles are the fix.
 *
 * And that every alert must be actionable. An alert with no response is training the team to
 * ignore alerts, which is the same failure [[automated-testing]] describes for flaky tests and
 * [[ci-cd]] for red builds — and it is worth meeting a third time.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

