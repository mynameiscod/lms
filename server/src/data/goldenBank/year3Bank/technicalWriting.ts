/**
 * TECHNICAL_WRITING — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can write something another engineer can act on. Not grammar, and not
 * length — whether the reader finishes with what they came for. Most engineering writing fails
 * because it was written from the author's knowledge rather than the reader's need.
 *
 * Bands: name the pieces, explain why the conventions exist, apply them to a described
 * document, diagnose writing that is failing its reader, and judge what is worth writing at all.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That you decide the reader before the first sentence. Everything else — how much to explain,
 * what to leave out, what order to put it in — follows from who is reading and what they will
 * do next. A document written for everybody serves nobody.
 *
 * That the conclusion goes first. Engineers write in the order they discovered things, and
 * readers want the answer and then the reasoning, in that order.
 *
 * And that documentation which drifts is worse than none, because a wrong instruction is
 * followed confidently. Anything hand-maintained rots, so what cannot be generated must be
 * short enough to keep true.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

