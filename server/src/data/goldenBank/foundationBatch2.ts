/**
 * Golden Bank blueprint — Batch 2: the five programming skills.
 *
 * EXECUTABLE REASONING, NOT SYNTAX TRIVIA. Every family here asks the student to work out what
 * a fragment DOES: what a variable holds, which branch runs, how many times a body executes,
 * what a call returns. Recall of spelling is admitted only where getting it wrong actually stops
 * a beginner — identifier rules, the difference between `/` and `//` — and even there the stem
 * shows code rather than asking about it in the abstract.
 *
 * ALL mcq_single, WITH CODE IN THE STEM. That is the platform decision and it costs nothing
 * here: "trace this and give the output" is a multiple-choice question whose options are the
 * results of specific slips. The item is only weak if the distractors are absurd, which is a
 * property of the distractors and not of the format.
 *
 * SEVERAL FAMILIES SHARE A FACT ON PURPOSE. Recognising that assignment is not equality, and
 * tracing a variable through four assignments, rest on the same fact and are not the same
 * measurement — one is answerable from a definition, the other only by tracing. They carry the
 * same factId and different familyIds, and sit in the same reassessment group so they are never
 * served together.
 *
 * DISTRACTORS ARE SLIPS, NOT NONSENSE. The value one iteration early. The first assignment
 * rather than the last. The integer answer where the language gives a float. What the code would
 * print if the update came before the output. Every wrong option should be reachable by one
 * identifiable mistake, so a wrong answer names the misconception.
 */

