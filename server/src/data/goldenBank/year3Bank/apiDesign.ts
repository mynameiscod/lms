/**
 * API_DESIGN — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can design an interface other people will build on and then live with the
 * consequences. REST_APIS (Year 2) covers the mechanics — verbs, status codes, how a request is
 * shaped. This is the level above: what to expose, what to promise, and how to change it once
 * somebody depends on it.
 *
 * Bands: name the pieces, explain why the conventions exist, apply them to a described feature,
 * diagnose an API that has become painful, and judge the calls where two designs are both
 * defensible.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That a published API is a promise you cannot take back unilaterally. Every question about
 * versioning, deprecation and additive change follows from that one fact, and students who have
 * only ever called APIs have never felt the weight of it.
 *
 * That the error design is half the API. Most of the effort goes into the success path and most
 * of the integrator's time goes into the failure path, which is the wrong way round.
 *
 * And that an API should expose the caller's model rather than your storage. A response that is
 * a database row means renaming a column is a breaking change — the same leak [[authorization]]
 * and [[software-architecture]] both run into from other directions.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

