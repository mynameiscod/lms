/**
 * DEVOPS_FUNDAMENTALS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student understands how code gets from a laptop to production repeatedly, safely,
 * and without a person remembering the steps. CLOUD_FUNDAMENTALS is about what you are running
 * on; this is about the path onto it — build, test, ship, watch, and undo.
 *
 * Bands: name the pieces of a pipeline, explain what automating each one buys, assemble one for
 * a requirement, diagnose the failures teams actually hit, and judge where the practices are
 * worth their cost.
 *
 * ── THE THREE POSITIONS THIS TAKES ────────────────────────────────────────────────────────
 *
 * That the value is repeatability, not speed. A pipeline is worth having because it does the
 * same thing every time, in an order nobody has to recall at 6pm on a Friday. Speed is a
 * pleasant consequence.
 *
 * That you deploy the artefact you tested. Rebuilding per environment ships something no test
 * ever saw, and "works in staging" then means very little. Configuration varies; the build
 * does not.
 *
 * And that being able to undo is worth more than being able to fix forwards under pressure.
 * Several bands turn on that: small releases, a rollback that is practised, and a monitor that
 * tells you which release to blame.
 */

