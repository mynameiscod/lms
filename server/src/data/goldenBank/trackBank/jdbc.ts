/**
 * JDBC — fifty items, ten at each band. Question ids GBT_JDBC_001 … GBT_JDBC_050.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can talk to a relational database from Java safely: get a connection the
 * right way, send parameterised SQL, read results including NULLs, keep a multi-statement change
 * atomic, and give every connection back. JPA and Spring Data sit on top of exactly this, and
 * their failures (pool exhaustion, half-applied changes, injection through a native query) are
 * JDBC failures underneath.
 *
 * Bands: name the pieces (Connection, URL, Statement, PreparedStatement, ResultSet, DataSource,
 * pool, DAO), explain why they work as they do, apply them to a described task, diagnose code
 * that leaks, injects or half-commits, and judge pool sizes, transaction scope and DAO shape.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That PreparedStatement is the default, not an optimisation: user input goes in as a bound
 * value and never into the SQL text. Where input must shape the SQL (a column to sort by), the
 * answer is a whitelist, because placeholders cannot stand for identifiers.
 *
 * That a connection is a scarce, borrowed resource. try-with-resources is the only reliable way
 * to return it, and a bigger pool is not the fix for a leak.
 *
 * That autoCommit is on by default, so two related updates are two transactions until you say
 * otherwise, and that a transaction should be short and never span a remote call.
 *
 * The items assume MySQL 8 with Connector/J and HikariCP (Spring Boot 3's default pool). None of
 * them needs a live database to answer; the behaviour asserted is what the JDBC API specifies.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */
