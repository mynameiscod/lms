/**
 * PYTHON_ERROR_HANDLING — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can decide what a failing program should DO. Year 1 teaches that try/except
 * stops a crash; this is the second-year question of when stopping the crash is the wrong answer,
 * and what a caller is owed when something goes wrong.
 *
 * Bands: name the machinery, explain what each part is for, write handlers for stated
 * requirements, diagnose the ways exception handling hides bugs, and judge where to catch, what
 * to catch, and when to let it fall over.
 *
 * ── THE THREE POSITIONS THIS TAKES ────────────────────────────────────────────────────────
 *
 * That the worst handler is the one that succeeds. `except: pass` turns a failure into a wrong
 * answer, and a wrong answer travels — through a report, into a decision — with nothing
 * anywhere saying it was ever a failure. Several bands turn on that.
 *
 * That catching broadly catches things you did not mean: a bare `except` swallows the typo in
 * the handler itself, the interrupt the user pressed, and the memory error that meant stop.
 *
 * And that an exception is part of an interface. What a function raises is as much a promise as
 * what it returns, and swallowing it internally removes the caller's ability to decide.
 */

