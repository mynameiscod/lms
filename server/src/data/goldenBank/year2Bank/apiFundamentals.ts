/**
 * API_FUNDAMENTALS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can consume and expose an API without being surprised by it. This is the
 * general skill — contracts, status codes, auth, errors, versioning — and REST_APIS is the
 * narrower one about designing resources and verbs. Kept apart because plenty of the APIs a
 * second-year meets are not REST at all.
 *
 * Bands: name the pieces, explain what each is for, use an API correctly, diagnose one that is
 * failing in a way the status code does not explain, and judge the contract decisions.
 *
 * ── THE TWO POSITIONS THIS TAKES ──────────────────────────────────────────────────────────
 *
 * That an API is a promise to people you cannot contact. Once something is published you do not
 * know who depends on it, so the only safe changes are additive, and the interesting judgement
 * is about what you can never take back. D5 is built on that.
 *
 * And that the network is the part beginners forget. A call can be slow, can fail halfway, can
 * succeed while the response is lost, and can be retried by something you do not control. That
 * is why timeouts and idempotency are D3 and D4 material rather than advanced topics.
 */

