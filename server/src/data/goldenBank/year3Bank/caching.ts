/**
 * CACHING — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can add a cache without creating a correctness problem. Caching is the
 * easiest performance win to reach for and the easiest to get quietly wrong: the system gets
 * faster immediately and starts serving stale or wrong data in ways that surface weeks later.
 *
 * Bands: name the pieces, explain what a cache trades away, apply one to a described system,
 * diagnose a cache that is misbehaving, and judge when caching is the wrong answer.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That a cache is a deliberate decision to serve possibly-stale data, and that the real design
 * question is how stale is acceptable. Students treat caching as free speed; the whole skill is
 * knowing what you gave up for it.
 *
 * That invalidation is the hard part, and that a time-to-live is not a weaker answer than
 * event-based invalidation — it is often the right one, because it is the one that cannot leak.
 * Several items push against the instinct that precise invalidation is always better.
 *
 * That caching per-user data in a shared cache is how one person sees another person's page.
 * The key must contain everything the value depends on, which is the same failure
 * [[dsa-dp]] describes for memoisation state — and it is worth meeting twice.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

