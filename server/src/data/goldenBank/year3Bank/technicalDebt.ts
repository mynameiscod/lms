/**
 * TECHNICAL_DEBT — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can tell debt from mess, decide what to do about it, and argue for that
 * decision to somebody who does not read code. [[refactoring]] is the technique for repaying
 * it; this is the judgement about whether, when and how much to repay — and when to borrow
 * deliberately.
 *
 * Bands: name the idea, explain why the metaphor holds and where it breaks, apply it to a
 * described situation, diagnose a codebase whose debt is being handled badly, and judge the
 * calls that are genuinely contested.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That deliberate debt is a legitimate engineering decision and accidental mess is not. Taking
 * a shortcut knowingly, recording it, and repaying it is how products ship. Calling careless
 * work "technical debt" launders it, and several items push on that distinction.
 *
 * That the interest is what matters, not the principal. Ugly code nobody touches costs nothing;
 * a tangle in the file changed every week costs a little on every change, forever.
 *
 * And that the case for repayment is made in delivery terms, not aesthetics. "This area takes
 * three days per change and would take one" is a sentence a manager can act on; "the code is
 * bad" is not.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

