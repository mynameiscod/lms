/**
 * AUTHENTICATION — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can answer "who is this request from?" safely. Authentication is the half
 * that establishes identity; AUTHORIZATION is the half that decides what that identity may do,
 * and the two are measured separately here because students routinely collapse them into one.
 *
 * Bands: name the pieces, explain why each exists, apply them to a described login, diagnose a
 * broken or unsafe flow, and judge the calls where the secure answer and the usable one differ.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That a password is never stored, only a slow hash of one. Several items turn on this and the
 * wrong answers are the ones students actually give — encrypt it, hash it with SHA-256, salt it
 * and stop there.
 *
 * That a token is a bearer of identity, which means holding it is being that person. Everything
 * about expiry, transport and storage follows from that single sentence.
 *
 * And that most real breaches are not broken cryptography. They are a reset flow with no rate
 * limit, an error message that says which half was wrong, or a session that never ends.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options within an item are written to similar lengths deliberately; the suite fails a bank
 * where correct answers run long, since that lets a student score by picking the longest one.
 */

