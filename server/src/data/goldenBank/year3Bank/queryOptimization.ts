/**
 * QUERY_OPTIMIZATION — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can find out why a query is slow rather than guessing. [[db-indexing]]
 * covers one remedy; this covers the diagnosis, and the two are separated deliberately because
 * a great many slow queries are not an indexing problem at all and adding an index makes them
 * no faster while costing every write.
 *
 * Bands: name the tools, explain what makes a query expensive, apply a fix to a described
 * query, diagnose slowness from symptoms, and judge when to optimise and when to leave it.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That you measure before you change anything. The plan and the timings tell you where the
 * cost is; intuition about which line looks expensive is wrong often enough to be worthless,
 * and several items reward reaching for evidence over reaching for a rewrite.
 *
 * That the N+1 problem is the most common real cause of a slow page, and it is invisible in
 * any single query's timings because each one is fast. It appears at three bands.
 *
 * And that the cheapest optimisation is asking for less — fewer rows, fewer columns, fewer
 * round trips. Students reach for index tuning and rewriting long before they check whether
 * the query needed to ask for all that in the first place.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

