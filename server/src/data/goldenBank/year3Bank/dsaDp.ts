/**
 * DSA_DP — dynamic programming. Fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can recognise that a problem has overlapping subproblems, define a state
 * that captures exactly what the answer depends on, and write a recurrence over it. The coding
 * is the easy half; nearly everybody who fails a DP question fails at the state definition.
 *
 * Bands: name the pieces, explain why memoising works at all, apply it to a described problem,
 * diagnose a recurrence that gives wrong answers or runs slowly, and judge when DP is the wrong
 * tool despite fitting.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That DP is recursion plus remembering, and nothing more mysterious. A student who sees the
 * recursion first and the table second will get there; one who starts by drawing a table and
 * hoping usually does not.
 *
 * That the state must contain everything the answer depends on and nothing else. Too little and
 * the cached value is wrong for the case that reuses it; too much and there is nothing to reuse.
 * Several D4 items are built on exactly that failure.
 *
 * And that the two preconditions are separate. Optimal substructure says the recurrence is
 * valid; overlapping subproblems says caching pays. A problem can have one without the other,
 * and knowing which is missing tells you what to reach for instead.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, because that can be scored without reading the question.
 */

