/**
 * NOSQL_CONCEPTS — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can choose a data store on evidence rather than fashion, and model data
 * correctly once they have. The Year-2 database skills cover relational modelling and SQL;
 * this covers the alternatives — what they give up, what they buy, and when the exchange is
 * worth making.
 *
 * Bands: name the families, explain what each trades, apply one to a described system,
 * diagnose a model that is fighting its store, and judge the choice itself.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That you model around the queries, not the entities. This is the genuine reversal from
 * relational thinking: in SQL you normalise and then query; in most NoSQL stores you write
 * down the queries first and shape the data to serve them.
 *
 * That "schemaless" means the schema is in the application rather than absent. Somebody still
 * assumes a shape, and without the database enforcing it, that assumption breaks silently.
 *
 * And that the default choice should usually still be a relational database. It is a genuinely
 * good general-purpose answer, and most NoSQL adoption is a decision nobody made on evidence.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

