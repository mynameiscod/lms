/**
 * JS_ASYNC — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student can reason about code that does not finish in the order it is written.
 * JS_BASICS covers the language; this is the narrower and harder question of what happens when
 * a value is not there yet — and what the runtime is doing in the meantime.
 *
 * Bands: name the pieces, explain what the event loop actually does, write code that awaits
 * correctly, diagnose the classic wrong answers, and judge sequential against concurrent when
 * both would work.
 *
 * ── THE THREE POSITIONS THIS TAKES ────────────────────────────────────────────────────────
 *
 * That `await` suspends a function, not the program. Most async bugs a second-year writes come
 * from believing the second thing — a loop that awaits each of fifty requests in turn is not
 * wrong, it is slow, and knowing the difference is the skill.
 *
 * That a forgotten `await` is the worst bug in the language, because it does not throw. It
 * returns a Promise where a value was expected, and the failure appears somewhere else, later,
 * as `undefined`. Several bands turn on spotting it.
 *
 * And that single-threaded does not mean one-thing-at-a-time. The runtime waits for nothing;
 * the JavaScript does. D4 and D5 are largely about what that distinction buys and what it
 * costs — including the case where it costs everything, a long synchronous loop that blocks
 * the one thread every other callback is queued behind.
 */

