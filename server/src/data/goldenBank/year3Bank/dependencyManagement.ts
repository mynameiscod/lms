/**
 * DEPENDENCY_MANAGEMENT — fifty items, ten at each band.
 *
 * ── WHAT THIS SKILL IS BEING MEASURED ON ──────────────────────────────────────────────────
 *
 * Whether a student treats the packages they install as code they are responsible for. Most of
 * a modern application is somebody else's work, and the decisions about which of it to adopt,
 * how to pin it and when to update it are engineering decisions that get made by default.
 *
 * Bands: name the pieces, explain why the conventions exist, apply them to a described
 * situation, diagnose a dependency problem, and judge the calls about what to take on.
 *
 * ── THE POSITIONS THIS TAKES ──────────────────────────────────────────────────────────────
 *
 * That a dependency is a permanent commitment, not a one-off saving. You have adopted its
 * bugs, its security advisories, its breaking changes and its maintainer's decisions about
 * the next five years, in exchange for not writing the code today.
 *
 * That the lock file is the build. The manifest says what you want; the lock says what you
 * got, and a build that ignores it is not reproducing anything.
 *
 * And that never updating is a decision with a cost, exactly as updating carelessly is. Four
 * deferred upgrades become one expensive project, and the security advisories accumulate while
 * you wait — a point [[technical-debt]] makes from the other direction.
 *
 * ── A NOTE ON OPTION LENGTH ───────────────────────────────────────────────────────────────
 *
 * Options are written to similar lengths on purpose; the suite fails a bank whose correct
 * answers run long, since that can be scored without reading the question.
 */

